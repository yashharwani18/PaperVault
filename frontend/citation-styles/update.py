"""Refresh the small offline CSL bundle from the official upstream repositories."""
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parent
STYLES = {
    'apa': 'apa.csl',
    'ieee': 'ieee.csl',
    'mla': 'modern-language-association.csl',
    'chicago': 'chicago-author-date.csl',
    'harvard': 'harvard-cite-them-right.csl',
    'vancouver': 'nlm-citation-sequence.csl',
}


def read(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'Khoj-offline-style-bundle'})
    with urllib.request.urlopen(request, timeout=40) as response:
        return response.read()


def main():
    manifest = {'sources': [], 'styles': STYLES}
    bundle = {}
    for repo, files in (
        ('styles', list(STYLES.values()) + ['README.md']),
        ('locales', ['locales-en-US.xml', 'locales-en-GB.xml', 'README.md']),
    ):
        revision = json.loads(read(f'https://api.github.com/repos/citation-style-language/{repo}/commits/master'))['sha']
        for filename in files:
            url = f'https://raw.githubusercontent.com/citation-style-language/{repo}/{revision}/{filename}'
            data = read(url)
            target = ROOT / (f'{repo}-{filename}' if filename == 'README.md' else filename)
            target.write_bytes(data)
            manifest['sources'].append({'path': target.name, 'url': url, 'sha256': hashlib.sha256(data).hexdigest()})
            if filename.endswith(('.csl', '.xml')):
                bundle[filename] = data.decode('utf-8')
    for filename in ['LICENSE', 'CPAL']:
        url = f'https://raw.githubusercontent.com/Juris-M/citeproc-js/master/{filename}'
        data = read(url)
        target = ROOT / f'citeproc-{filename}.txt'
        target.write_bytes(data)
        manifest['sources'].append({'path': target.name, 'url': url, 'sha256': hashlib.sha256(data).hexdigest()})
    (ROOT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    (ROOT / 'bundle.js').write_text('// Generated by update.py. Upstream files are unmodified; see manifest.json and NOTICES.md.\nexport default ' + json.dumps(bundle, ensure_ascii=False) + ';\n', encoding='utf-8')
    print('Bundled', len(bundle), 'offline CSL styles and locales')


if __name__ == '__main__':
    main()
